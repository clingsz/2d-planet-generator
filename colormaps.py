ALIASES = {"terrain": "earth"}


def list_colormaps():
    return ["grayscale"] + sorted(GRADIENTS.keys())


def apply_colormap(height, name="terrain"):
    """height: (w, h) array in [0, 1]. Returns (w, h, 3) uint8 RGB array."""
    if name == "grayscale":
        g = np.clip(height * 255, 0, 255).astype(np.uint8)
        return np.stack([g, g, g], axis=-1)

    name = ALIASES.get(name, name)
    grad = GRADIENTS.get(name)
    if grad is None:
        raise ValueError(f"unknown colormap '{name}', have {list_colormaps()}")

    pos = np.array([p for p, _ in grad])
    cols = np.array([c for _, c in grad])  # (n, 3) floats 0..1
    r = np.interp(height, pos, cols[:, 0])
    g = np.interp(height, pos, cols[:, 1])
    b = np.interp(height, pos, cols[:, 2])
    rgb = np.stack([r, g, b], axis=-1)
    return np.clip(rgb * 255, 0, 255).astype(np.uint8)
